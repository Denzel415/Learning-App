"""Generates data/crm.js, the sample CRM data the course queries run against.
Run: python3 tools/make_data.py   (same seed gives the same data every time)"""
import json, random, pathlib
random.seed(415)
names = ["Northwind Labs","Harbor Freight Systems","Brightpath Health","Cobalt Labs","Meridian Pay","Ironclad Logistics",
"Lumen Retail Group","Sagebrush Software","Quill Analytics","Tidewater Manufacturing","Pinecone Labs","Atlas Ledger",
"Verde Clinics","Kestrel Cloud","Foundry Works","Marlow & Finch","Redwood Payments","Signal Peak Software","Orchard Supply Co",
"Halcyon Health","Bluebird Freight","Copperline Manufacturing","Novo Labs","Fathom Data","Juniper Retail","Stonebridge Capital Tech",
"Driftwood Outfitters","Vanta Robotics","Clearwater Care","Summit Route","Echo Park Software","Granite Tooling","Parcelwise",
"Mosaic Pay","Lighthouse Labs","Thistle Health","Rivet Industrial","Open Range Software","Cinder Commerce","Wayfinder Logistics"]
ind = {"Labs":"Software","Software":"Software","Cloud":"Software","Analytics":"Software","Data":"Software","Pay":"Fintech","Ledger":"Fintech",
"Payments":"Fintech","Capital":"Fintech","Health":"Healthcare","Clinics":"Healthcare","Care":"Healthcare","Manufacturing":"Manufacturing",
"Works":"Manufacturing","Tooling":"Manufacturing","Industrial":"Manufacturing","Robotics":"Manufacturing","Retail":"Retail","Supply":"Retail",
"Outfitters":"Retail","Commerce":"Retail","Finch":"Retail","Freight":"Logistics","Logistics":"Logistics","Route":"Logistics","Parcelwise":"Logistics","Systems":"Logistics"}
states = ["CA","CA","CA","NY","NY","TX","TX","WA","IL","CO","MA"]
owners = ["Priya Shah","Marcus Reed","Elena Ortiz","Tom Nakamura","Dana Whitfield"]
rows, used = [], set()
for i, n in enumerate(names, 1):
    industry = next(v for k, v in ind.items() if k in n)
    emp = random.choice([35,60,85,120,150,210,260,340,420,480,560,640,820,1100,1500,2400,3800])
    rev = emp * random.randint(90, 260) * 1000 + i * 1000
    while rev in used: rev += 1000
    used.add(rev)
    owner = None if i in (4, 11, 17, 23, 30, 36) else random.choice(owners)
    created = f"{random.choice([2023,2024,2024,2025,2025,2026])}-{random.randint(1,9):02d}-{random.randint(1,28):02d}"
    rows.append([i, n, industry, random.choice(states), emp, rev, owner, created])
out = {"accounts": {"columns": [["id","INTEGER"],["name","TEXT"],["industry","TEXT"],["state","TEXT"],["employees","INTEGER"],
    ["annual_revenue","INTEGER"],["owner","TEXT"],["created_at","TEXT"]], "rows": rows}}
p = pathlib.Path(__file__).resolve().parent.parent / "data" / "crm.js"
p.write_text("// Generated by tools/make_data.py. Edit the script, not this file.\nwindow.CRM_DATA = " + json.dumps(out, indent=None, separators=(",", ":")).replace("],[", "],\n[") + ";\n")
print(len(rows), "accounts")
